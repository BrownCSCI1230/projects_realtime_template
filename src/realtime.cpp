void Realtime::finish() {
    killTimer(m_timer);
    this->makeCurrent();

    // Students: anything requiring OpenGL calls when the program exits should be done here
    if (m_gl_realtime) m_gl_realtime.reset();

    this->doneCurrent();
}


void Realtime::initializeGL() {
    m_devicePixelRatio = this->devicePixelRatio();

    m_timer = startTimer(1000/60);
    m_elapsedTimer.start();

    // All openGL calls must be done after initializeGL is called
    // otherwise we'll have a rough time.
    m_gl_realtime = std::make_unique<GlRealtime>(
        size().width(),
        size().height(),
        m_devicePixelRatio
    );

}

void Realtime::paintGL() {
    // Students: anything requiring OpenGL calls every frame should be done here
    if (m_gl_realtime) {
        m_gl_realtime->paint();
    }

}

void Realtime::resizeGL(int w, int h) {
    if (m_gl_realtime) m_gl_realtime->resize(size().width(), size().height());
}


void Realtime::sceneChanged() {
    // TA Solution:
    if(settings.sceneFilePath != "" && m_gl_realtime) {
        this->makeCurrent();
        m_gl_realtime->loadScene(
            settings.sceneFilePath,
            settings.nearPlane,
            settings.farPlane
        );
    }
    update(); // Asks for a PaintGL() call to occur
}

void Realtime::settingsChanged() {
    if(m_gl_realtime) {
        this->makeCurrent();
        m_gl_realtime->settingsChanged();
        update();
    }
}

